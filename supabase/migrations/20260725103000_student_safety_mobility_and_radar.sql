-- Student Safety Mobility and consent-based campus radar.
-- The existing incident and GPS map systems remain authoritative.

create table if not exists public.safety_mobility_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  campus public.campus_location not null,
  mode text not null check (mode in ('in_transit', 'night_travel', 'find_my_phone')),
  status text not null default 'active' check (status in ('active', 'paused', 'completed', 'cancelled', 'alerted', 'expired')),
  transport_type text,
  vehicle_details text,
  destination_label text,
  expected_end_at timestamptz,
  share_scope text not null default 'trusted_circle' check (share_scope in ('private', 'trusted_circle', 'campus_security')),
  consent_at timestamptz not null default now(),
  last_location_at timestamptz,
  incident_id uuid references public.incidents(id) on delete set null,
  alert_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  ended_at timestamptz
);

create table if not exists public.safety_mobility_location_updates (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.safety_mobility_sessions(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy_meters double precision,
  heading_degrees double precision,
  speed_mps double precision,
  battery_percent numeric(5,2),
  readable_location text,
  recorded_at timestamptz not null default now()
);

create table if not exists public.safety_mobility_events (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.safety_mobility_sessions(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  event_type text not null check (event_type in ('started', 'location', 'paused', 'resumed', 'alerted', 'completed', 'cancelled', 'expired')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.student_safety_presence (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  campus public.campus_location not null,
  visibility text not null default 'off' check (visibility in ('off', 'campus_approximate', 'campus_exact')),
  status_message text,
  latitude double precision,
  longitude double precision,
  accuracy_meters double precision,
  zone_label text,
  sharing_until timestamptz,
  exact_location_consent_at timestamptz,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint student_safety_presence_coordinate_pair check (
    (latitude is null and longitude is null)
    or (latitude is not null and longitude is not null)
  )
);

create index if not exists safety_mobility_sessions_user_status_idx
  on public.safety_mobility_sessions(user_id, status, created_at desc);
create index if not exists safety_mobility_sessions_campus_alert_idx
  on public.safety_mobility_sessions(campus, status, last_location_at desc);
create index if not exists safety_mobility_updates_session_time_idx
  on public.safety_mobility_location_updates(session_id, recorded_at desc);
create index if not exists student_safety_presence_campus_seen_idx
  on public.student_safety_presence(campus, visibility, last_seen_at desc);

alter table public.safety_mobility_sessions enable row level security;
alter table public.safety_mobility_location_updates enable row level security;
alter table public.safety_mobility_events enable row level security;
alter table public.student_safety_presence enable row level security;

