create or replace function public.traffic_create_visitor_pass(
  p_visitor_name text,
  p_visitor_email text,
  p_visitor_phone text,
  p_vehicle_registration text,
  p_vehicle_make text,
  p_vehicle_colour text,
  p_campus public.campus_location,
  p_host_name text,
  p_host_department text,
  p_visit_purpose text,
  p_visit_date date,
  p_expected_arrival time
)
returns table (
  pass_id uuid,
  reference_code text,
  tracking_token text,
  pass_status public.traffic_pass_status,
  submitted_at timestamptz
)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_name text := nullif(btrim(p_visitor_name), '');
  v_email text := nullif(lower(btrim(p_visitor_email)), '');
  v_phone text := regexp_replace(coalesce(p_visitor_phone, ''), '[^0-9+]', '', 'g');
  v_registration text := upper(regexp_replace(coalesce(p_vehicle_registration, ''), '\s+', ' ', 'g'));
  v_reference text;
  v_token text := replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', '');
  v_fingerprint text;
  v_row public.traffic_visitor_passes;
begin
  if v_name is null or char_length(v_name) not between 2 and 120 then
    raise exception 'Enter the visitor full name';
  end if;
  if v_email is not null and (char_length(v_email) > 160 or v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$') then
    raise exception 'Enter a valid email address';
  end if;
  if char_length(v_phone) not between 7 and 24 then
    raise exception 'Enter a valid phone number';
  end if;
  if char_length(v_registration) not between 2 and 20 then
    raise exception 'Enter a valid vehicle registration';
  end if;
  if char_length(coalesce(p_host_name, '')) not between 2 and 120 then
    raise exception 'Enter the host name';
  end if;
  if char_length(coalesce(p_visit_purpose, '')) not between 3 and 500 then
    raise exception 'Describe the purpose of the visit';
  end if;
  if p_visit_date < current_date or p_visit_date > current_date + 120 then
    raise exception 'Visit date must be within the next 120 days';
  end if;

  v_fingerprint := encode(digest(coalesce(v_email, '') || '|' || v_phone, 'sha256'), 'hex');
  if (
    select count(*)
    from public.traffic_visitor_passes
    where contact_fingerprint = v_fingerprint
      and created_at > now() - interval '1 hour'
  ) >= 3 then
    raise exception 'Too many recent parking requests. Try again later or contact the Traffic department.';
  end if;

  if exists (
    select 1 from public.traffic_visitor_passes
    where visit_date = p_visit_date
      and campus = p_campus
      and vehicle_registration = v_registration
      and status not in ('rejected', 'cancelled', 'expired')
  ) then
    raise exception 'A parking request already exists for this vehicle, campus and date';
  end if;

  v_reference := 'VIS-' || to_char(p_visit_date, 'YYMMDD') || '-' ||
    upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6));

  insert into public.traffic_visitor_passes (
    reference_code, tracking_token_hash, contact_fingerprint,
    visitor_name, visitor_email, visitor_phone,
    vehicle_registration, vehicle_make, vehicle_colour,
    campus, host_name, host_department, visit_purpose,
    visit_date, expected_arrival
  ) values (
    v_reference, encode(digest(v_token, 'sha256'), 'hex'), v_fingerprint,
    v_name, v_email, v_phone,
    v_registration, nullif(btrim(p_vehicle_make), ''), nullif(btrim(p_vehicle_colour), ''),
    p_campus, btrim(p_host_name), nullif(btrim(p_host_department), ''), btrim(p_visit_purpose),
    p_visit_date, p_expected_arrival
  ) returning * into v_row;

  return query select v_row.id, v_row.reference_code, v_token, v_row.status, v_row.created_at;
end;
$$;

