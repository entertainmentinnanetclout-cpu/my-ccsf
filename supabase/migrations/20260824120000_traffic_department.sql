create or replace function public.traffic_request_student_permit(
  p_campus public.campus_location,
  p_vehicle_registration text,
  p_vehicle_make text,
  p_vehicle_colour text
)
returns public.traffic_student_permits
language plpgsql
security definer
set search_path = public, private
as $$
declare
  v_profile public.profiles;
  v_registration text := upper(regexp_replace(coalesce(p_vehicle_registration, ''), '\s+', ' ', 'g'));
  v_existing public.traffic_student_permits;
  v_row public.traffic_student_permits;
begin
  if auth.uid() is null or not public.has_role(auth.uid(), 'student'::public.user_role) then
    raise exception 'Student authentication is required';
  end if;
  select * into v_profile from public.profiles where id = auth.uid();
  if v_profile.campus is null or v_profile.campus <> p_campus then
    raise exception 'The permit campus must match the verified student profile';
  end if;
  if char_length(v_registration) not between 2 and 20 then
    raise exception 'Enter a valid vehicle registration';
  end if;

  select * into v_existing
  from public.traffic_student_permits
  where student_id = auth.uid()
  for update;

  if found and v_existing.status in ('active', 'suspended') then
    raise exception 'An issued permit must be changed by the Traffic department';
  end if;

  insert into public.traffic_student_permits (
    student_id, campus, vehicle_registration, vehicle_make, vehicle_colour, status
  ) values (
    auth.uid(), p_campus, v_registration,
    nullif(btrim(p_vehicle_make), ''), nullif(btrim(p_vehicle_colour), ''), 'pending'
  )
  on conflict (student_id) do update set
    campus = excluded.campus,
    vehicle_registration = excluded.vehicle_registration,
    vehicle_make = excluded.vehicle_make,
    vehicle_colour = excluded.vehicle_colour,
    status = 'pending',
    decision_notes = null,
    updated_at = now()
  returning * into v_row;

  return v_row;
end;
$$;

create or replace function public.traffic_update_visitor_pass_status(
  p_pass_id uuid,
  p_status public.traffic_pass_status,
  p_gate_name text default null,
  p_notes text default null
)
returns void
language plpgsql
security definer
set search_path = public, private
as $$
declare
  v_pass public.traffic_visitor_passes;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;

  select * into v_pass
  from public.traffic_visitor_passes
  where id = p_pass_id
  for update;
  if not found then raise exception 'Visitor pass not found'; end if;

  if not (
    public.has_role(auth.uid(), 'admin'::public.user_role)
    or (
      public.has_role(auth.uid(), 'security'::public.user_role)
      and public.has_campus_access(auth.uid(), v_pass.campus)
    )
  ) then
    raise exception 'Not authorised for this campus';
  end if;

  if not (
    (v_pass.status = 'pending' and p_status in ('approved', 'rejected', 'cancelled'))
    or (v_pass.status = 'approved' and p_status in ('checked_in', 'cancelled', 'expired'))
    or (v_pass.status = 'checked_in' and p_status in ('checked_out', 'cancelled'))
    or (v_pass.status = p_status)
  ) then
    raise exception 'Unsupported visitor pass status transition';
  end if;

  update public.traffic_visitor_passes set
    status = p_status,
    decision_notes = case when p_notes is null then decision_notes else nullif(btrim(p_notes), '') end,
    approved_by = case when p_status = 'approved' then auth.uid() else approved_by end,
    approved_at = case when p_status = 'approved' then coalesce(approved_at, now()) else approved_at end,
    checked_in_at = case when p_status = 'checked_in' then coalesce(checked_in_at, now()) else checked_in_at end,
    checked_out_at = case when p_status = 'checked_out' then coalesce(checked_out_at, now()) else checked_out_at end,
    updated_at = now()
  where id = p_pass_id;

  insert into public.traffic_gate_events (
    visitor_pass_id, event_type, gate_name, notes, recorded_by
  ) values (
    p_pass_id, p_status, nullif(btrim(p_gate_name), ''), nullif(btrim(p_notes), ''), auth.uid()
  );
end;
$$;

create or replace function public.traffic_update_student_permit_status(
  p_permit_id uuid,
  p_status public.traffic_student_permit_status,
  p_notes text default null,
  p_valid_until date default null
)
returns void
language plpgsql
security definer
set search_path = public, private
as $$
declare
  v_permit public.traffic_student_permits;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;

  select * into v_permit
  from public.traffic_student_permits
  where id = p_permit_id
  for update;
  if not found then raise exception 'Student permit not found'; end if;

  if not (
    public.has_role(auth.uid(), 'admin'::public.user_role)
    or (
      public.has_role(auth.uid(), 'security'::public.user_role)
      and public.has_campus_access(auth.uid(), v_permit.campus)
    )
  ) then
    raise exception 'Not authorised for this campus';
  end if;

  if p_status not in ('active', 'suspended', 'expired', 'rejected') then
    raise exception 'Unsupported student permit status';
  end if;

  update public.traffic_student_permits set
    status = p_status,
    decision_notes = nullif(btrim(p_notes), ''),
    permit_number = case
      when p_status = 'active' then coalesce(
        permit_number,
        'STU-' || upper(substr(replace(v_permit.campus::text, '_', ''), 1, 4)) ||
          '-' || to_char(current_date, 'YY') || '-' ||
          upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6))
      )
      else permit_number
    end,
    valid_from = case when p_status = 'active' then coalesce(valid_from, current_date) else valid_from end,
    valid_until = case
      when p_status = 'active' then coalesce(p_valid_until, valid_until, current_date + 365)
      else valid_until
    end,
    issued_by = case when p_status = 'active' then auth.uid() else issued_by end,
    updated_at = now()
  where id = p_permit_id;
end;
$$;

