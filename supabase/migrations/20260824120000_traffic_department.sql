  bucket_id = 'traffic-permit-templates'
  and (
    public.has_role((select auth.uid()), 'admin'::public.user_role)
    or public.has_role((select auth.uid()), 'security'::public.user_role)
  )
);

create policy traffic_staff_upload_template_files
on storage.objects for insert to authenticated
with check (
  bucket_id = 'traffic-permit-templates'
  and (storage.foldername(name))[2] = (select auth.uid())::text
  and (
    public.has_role((select auth.uid()), 'admin'::public.user_role)
    or public.has_role((select auth.uid()), 'security'::public.user_role)
  )
);

create policy traffic_staff_update_own_template_files
on storage.objects for update to authenticated
using (
  bucket_id = 'traffic-permit-templates'
  and owner_id = (select auth.uid())::text
)
with check (
  bucket_id = 'traffic-permit-templates'
  and owner_id = (select auth.uid())::text
);

create policy traffic_staff_delete_own_template_files
on storage.objects for delete to authenticated
using (
  bucket_id = 'traffic-permit-templates'
  and (
    owner_id = (select auth.uid())::text
    or public.has_role((select auth.uid()), 'admin'::public.user_role)
  )
);

