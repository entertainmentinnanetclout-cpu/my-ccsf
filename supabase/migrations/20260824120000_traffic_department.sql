-- CCSF Traffic department: visitor parking, student permits, gate events,
-- road-safety notices and configurable physical-permit templates.

create type public.traffic_pass_status as enum (
  'pending',
  'approved',
  'rejected',
  'checked_in',
  'checked_out',
  'expired',
  'cancelled'
);

create type public.traffic_student_permit_status as enum (
  'pending',
  'active',
  'suspended',
  'expired',
  'rejected'
);

create type public.traffic_template_status as enum ('draft', 'active', 'archived');
create type public.traffic_permit_kind as enum ('student', 'visitor');

create table public.traffic_visitor_passes (
  id uuid primary key default gen_random_uuid(),
  reference_code text not null unique,
  tracking_token_hash text not null,
  contact_fingerprint text not null,
  visitor_name text not null check (char_length(visitor_name) between 2 and 120),
  visitor_email text,
  visitor_phone text not null check (char_length(visitor_phone) between 7 and 24),
  vehicle_registration text not null check (char_length(vehicle_registration) between 2 and 20),
  vehicle_make text,
  vehicle_colour text,
  campus public.campus_location not null,
  host_name text not null check (char_length(host_name) between 2 and 120),
  host_department text,
  visit_purpose text not null check (char_length(visit_purpose) between 3 and 500),
  visit_date date not null,
  expected_arrival time not null,
  status public.traffic_pass_status not null default 'pending',
  decision_notes text,
  approved_by uuid references public.profiles(id) on delete set null,
  approved_at timestamptz,
  checked_in_at timestamptz,
  checked_out_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.traffic_student_permits (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null unique references public.profiles(id) on delete cascade,
  campus public.campus_location not null,
  vehicle_registration text not null check (char_length(vehicle_registration) between 2 and 20),
  vehicle_make text,
  vehicle_colour text,
  permit_number text unique,
  status public.traffic_student_permit_status not null default 'pending',
  valid_from date,
  valid_until date,
  decision_notes text,
  issued_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint traffic_student_permit_dates check (
    valid_from is null or valid_until is null or valid_until >= valid_from
  )
);

create table public.traffic_permit_templates (
  id uuid primary key default gen_random_uuid(),
  campus public.campus_location,
  permit_kind public.traffic_permit_kind not null,
  name text not null check (char_length(name) between 2 and 100),
  storage_path text not null unique,
  status public.traffic_template_status not null default 'draft',
  notes text,
  created_by uuid not null references public.profiles(id) on delete restrict,
  activated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.traffic_gate_events (
  id bigint generated by default as identity primary key,
  visitor_pass_id uuid not null references public.traffic_visitor_passes(id) on delete cascade,
  event_type public.traffic_pass_status not null,
  gate_name text,
  notes text,
  recorded_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table public.traffic_road_safety_notices (
  id uuid primary key default gen_random_uuid(),
  campus public.campus_location,
  title text not null check (char_length(title) between 3 and 120),
  summary text not null check (char_length(summary) between 3 and 300),
  severity text not null default 'information' check (severity in ('information', 'caution', 'urgent')),
  is_published boolean not null default false,
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint traffic_notice_dates check (ends_at is null or ends_at > starts_at)
);

